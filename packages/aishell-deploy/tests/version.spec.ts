/**
 * The version a deployment snapshot records.
 *
 * The field exists so an old workspace can be traced to the release that wrote
 * it. A constant that never changes answers that question with a wrong answer,
 * which is what happened: `src/version.ts` was hand-written and read
 * `aishell-deploy 0.1.0` while the package shipped as `0.0.17`, through every
 * release in between.
 *
 * So the value is generated at build time, and this test pins the generation
 * rather than the number: whatever the manifest says today, the recorded
 * version says the same.
 */

import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

import { SERVER_VERSION } from '../src/version.ts'

const manifest = JSON.parse(
  readFileSync(join(import.meta.dirname, '..', 'package.json'), 'utf8'),
) as { version: string }

describe('SERVER_VERSION', () => {
  it('names the version this package actually ships as', () => {
    // Not "0.1.0", not "dev" — the manifest's own version. A mismatch means
    // `src/version.ts` is stale, and running the build regenerates it.
    expect(SERVER_VERSION).toBe(`aishell-deploy ${manifest.version}`)
  })

  it('is regenerated by the build, so it cannot drift again', () => {
    // The build script is what keeps the two in step; this asserts the wiring
    // exists rather than trusting that someone remembers it.
    const scripts = JSON.parse(
      readFileSync(join(import.meta.dirname, '..', 'package.json'), 'utf8'),
    ) as { scripts: Record<string, string> }
    expect(scripts.scripts['build:bundle']).toContain('write-deploy-version.mjs')
  })
})