#!/usr/bin/env node
/**
 * Write the package's own version into a source file, before the bundle is
 * built.
 *
 * ## Why the version cannot be read at runtime
 *
 * `package.json` is not in the bundle. tsdown emits `lib/index.js` and its
 * declarations; a `createRequire(import.meta.url)` looking for the manifest
 * would resolve against `lib/`, which holds no manifest, and every deployment
 * snapshot would then record `undefined` or throw. Resolving it from the source
 * tree instead would be worse: it would work in development and fail the
 * moment the package is installed from a tarball.
 *
 * So the value is substituted at build time, which is also the only point where
 * it is known to be the version that ships.
 *
 * ## Why the file is generated and not hand-written
 *
 * A hand-written constant drifts from the manifest silently, and the only
 * consumer of the field is tracing a workspace back to the code that wrote it.
 * A value that never changes answers that question with a wrong answer, and
 * nothing fails when it does.
 *
 * The generated file is committed like the other build artifacts this repository
 * keeps, and rewritten by `build:bundle` so the two cannot disagree.
 *
 * @module scripts/write-deploy-version
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

/** Repository root, derived from this file so the script runs from anywhere. */
const ROOT = fileURLToPath(new URL('..', import.meta.url))

/** The package whose version this writes. */
const PACKAGE = join(ROOT, 'packages', 'aishell-deploy')

const manifest = JSON.parse(readFileSync(join(PACKAGE, 'package.json'), 'utf8'))
if (typeof manifest.version !== 'string' || manifest.version === '') {
  console.error('[version] packages/aishell-deploy/package.json has no version')
  process.exit(1)
}

const text = `/**
 * The version recorded in a deployment's \`.deployment.json\`.
 *
 * GENERATED by \`scripts/write-deploy-version.mjs\` — do not edit. It is
 * rewritten on every build from the package manifest, so the two cannot
 * disagree; a hand-written value here would drift from the version that
 * actually ships, and the field exists to make that traceable.
 *
 * A deployment snapshot names the code that wrote it, so an old workspace can be
 * traced to the release that produced it.
 *
 * @module @huaweidevtools/aishell-dsh-deploy/version
 */

/**
 * What a snapshot records as \`server_version\`.
 *
 * The field name is fixed by \`.deployment.json\`'s published shape — workspaces
 * written by earlier releases carry it — so it is kept even though there is no
 * server.
 */
export const SERVER_VERSION = 'aishell-deploy ${manifest.version}'
`

writeFileSync(join(PACKAGE, 'src', 'version.ts'), text, 'utf8')
console.log(`[version] wrote src/version.ts: aishell-deploy ${manifest.version}`)