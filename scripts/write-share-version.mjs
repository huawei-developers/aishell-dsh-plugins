#!/usr/bin/env node
/**
 * Write this package's own version into a source file, before the bundle is
 * built.
 *
 * ## Why the value cannot be read at runtime
 *
 * `package.json` is not in the bundle. tsdown emits `lib/index.js` and its
 * declarations; resolving the manifest from `lib/` would find nothing, and
 * resolving it from the source tree would work in development and fail the
 * moment the package is installed from a tarball.
 *
 * So the value is substituted at build time, which is also the only point where
 * it is known to be the version that ships.
 *
 * ## Why the file is generated rather than written by hand
 *
 * A hand-written constant drifts from the manifest silently. This one is
 * stamped into every share package — `scripts/bump-version.mjs` moves the
 * manifest, and a stale constant would make every link claim the wrong writer,
 * with nothing failing.
 *
 * The generated file is committed like the other build artifacts this repository
 * keeps, and rewritten by `build:bundle` so the two cannot disagree.
 *
 * @module scripts/write-share-version
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

/** Repository root, derived from this file so the script runs from anywhere. */
const ROOT = fileURLToPath(new URL('..', import.meta.url))

/** The package whose version this writes. */
const PACKAGE = join(ROOT, 'packages', 'aishell-share')

const manifest = JSON.parse(readFileSync(join(PACKAGE, 'package.json'), 'utf8'))
if (typeof manifest.version !== 'string' || manifest.version === '') {
  console.error('[version] packages/aishell-share/package.json has no version')
  process.exit(1)
}

const text = `/**
 * The version stamped into every share package.
 *
 * GENERATED by \`scripts/write-share-version.mjs\` — do not edit. It is
 * rewritten on every build from the package manifest, so the two cannot
 * disagree; a hand-written value here would drift from the version that
 * actually ships.
 *
 * A share package names the client that wrote it, so a receiver reading a
 * link that will not open can tell which writer produced it. It is
 * diagnostic only: the importer does not compare versions, because the event
 * envelope already decides what this build can interpret.
 *
 * @module @huaweidevtools/aishell-dsh-share/version
 */

/** This build's version, as stamped from the package manifest. */
export const VERSION = '${manifest.version}'
`

writeFileSync(join(PACKAGE, 'src', 'version.ts'), text, 'utf8')
console.log(`[version] wrote src/version.ts: aishell-share ${manifest.version}`)